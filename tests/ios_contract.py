"""The iOS app's side of the notebook contract, written from `redline.model.notebook_views`.

The views stay declared once, in Python. This module derives, under `ios/RedlineKit/`:

- `Sources/RedlineKit/Notebook/NotebookViews.swift`: one Codable struct per TypedDict, one
  enum per Literal (with an `unknown` case, so that a value the server adds later does not
  break a screen), one enum per tagged union;
- `Tests/RedlineKitTests/Fixtures/<screen>.json`: the payloads of `notebook_payloads.SCREENS`;
- `Tests/RedlineKitTests/NotebookContractTests.swift`: one test per screen, which decodes its
  payload and encodes it back to the same JSON, so that no key is dropped in silence.

It also writes the palette of tests/ios_palette.py. `python tests/ios_contract.py` rewrites
everything; tests/test_ios_contract.py fails while any file differs from what is written.
"""

from __future__ import annotations

import json
import keyword
import re
import types
import typing
from collections.abc import Iterator
from pathlib import Path
from typing import Any

import ios_palette
from notebook_payloads import SCREENS

from redline.model import notebook_views as views

IOS = Path(__file__).resolve().parents[1] / "ios"
ROOT = IOS / "RedlineKit"
MODELS = ROOT / "Sources" / "RedlineKit" / "Notebook" / "NotebookViews.swift"
FIXTURES = ROOT / "Tests" / "RedlineKitTests" / "Fixtures"
CONTRACT_TESTS = ROOT / "Tests" / "RedlineKitTests" / "NotebookContractTests.swift"
HEADER = "// Generated by tests/ios_contract.py from src/redline/model/notebook_views.py: do not edit.\n"

SCALARS = {str: "String", int: "Int", float: "Double", bool: "Bool"}
SWIFT_KEYWORDS = {
    "any", "as", "associatedtype", "break", "case", "catch", "class", "continue", "default",
    "defer", "deinit", "do", "else", "enum", "extension", "fallthrough", "false", "fileprivate",
    "for", "func", "guard", "if", "import", "in", "init", "inout", "internal", "is", "let",
    "nil", "open", "operator", "private", "protocol", "public", "repeat", "rethrows", "return",
    "self", "some", "static", "struct", "subscript", "super", "switch", "throw", "throws",
    "true", "try", "typealias", "var", "where", "while",
}
#: Case names that would read as something else: `.none` is also `Optional.none`.
AMBIGUOUS_CASES = {"none", "some", "unknown"}
#: Nested type names Swift refuses or that would shadow what the generated code uses.
RESERVED_TYPES = {"Type", "Protocol", "Self", "String", "Int", "Double", "Bool", "CodingKeys",
                  "JSONValue", "Notebook"}
IDENTIFIER = re.compile(r"[A-Za-z_][A-Za-z0-9_]*")


def camel(name: str, upper: bool = False) -> str:
    parts = [part for part in re.split(r"[_\-\s]+", name) if part]
    text = parts[0].lower() if not upper else parts[0][:1].upper() + parts[0][1:]
    text += "".join(part[:1].upper() + part[1:] for part in parts[1:])
    if not IDENTIFIER.fullmatch(text):
        raise ValueError(f"{name!r} gives no Swift identifier")
    return text


def property_name(key: str) -> str:
    name = camel(key)
    return f"`{name}`" if name in SWIFT_KEYWORDS else name


def case_name(value: str) -> str:
    name = camel(value)
    if name in AMBIGUOUS_CASES:
        return name + "Value"
    return f"`{name}`" if name in SWIFT_KEYWORDS or keyword.iskeyword(name) else name


def nested_type_name(key: str) -> str:
    name = camel(key, upper=True)
    return name + "Value" if name in RESERVED_TYPES else name


# ------------------------------------------------------------ reading the views
def typeddicts() -> list[type]:
    return [value for value in vars(views).values()
            if isinstance(value, type) and typing.is_typeddict(value)]


def unions() -> dict[tuple[type, ...], str]:
    """The tagged unions the module names (`Ask = WakeAsk | CellsAsk | ...`), by members."""
    named = {}
    for name, value in vars(views).items():
        if isinstance(value, types.UnionType):
            members = typing.get_args(value)
            if all(typing.is_typeddict(member) for member in members):
                named[members] = name
    return named


def discriminator(members: tuple[type, ...]) -> tuple[str, dict[type, tuple[str, ...]]] | None:
    """The key every member types as a Literal, with values no two members share; None
    when the union is untagged."""
    hints = [typing.get_type_hints(member) for member in members]
    for key in hints[0]:
        values = [typing.get_args(hint.get(key)) if typing.get_origin(hint.get(key)) is typing.Literal
                  else None for hint in hints]
        if all(values) and len({v for group in values if group for v in group}) == sum(
                len(group) for group in values if group):
            return key, {member: group for member, group in zip(members, values, strict=True) if group}
    return None


def member_case(member: type, members: tuple[type, ...], union: str) -> str:
    name = member.__name__
    if name.endswith(union) and name != union:
        return case_name(name[: -len(union)])
    prefix = ""
    for letters in zip(*(m.__name__ for m in members), strict=False):
        if len(set(letters)) > 1:
            break
        prefix += letters[0]
    return case_name(name[len(prefix):])


# ------------------------------------------------------------ writing Swift
class Struct:
    """One TypedDict as a Swift struct, with the Literal enums its fields need."""

    def __init__(self, cls: type, named_unions: dict[tuple[type, ...], str]):
        self.cls = cls
        self.unions = named_unions
        self.enums: dict[str, tuple[str, ...]] = {}

    def swift_type(self, hint: Any, key: str) -> tuple[str, bool]:
        """The Swift type of a field, and whether JSON null is allowed."""
        origin = typing.get_origin(hint)
        if origin in (typing.Union, types.UnionType):
            options = tuple(option for option in typing.get_args(hint) if option is not type(None))
            nullable = len(options) < len(typing.get_args(hint))
            if len(options) == 1:
                return self.swift_type(options[0], key)[0], nullable
            if options in self.unions:
                return self.unions[options], nullable
            raise ValueError(f"{self.cls.__name__}.{key}: unsupported union {hint}")
        if hint is Any:
            return "JSONValue", False
        if hint in SCALARS:
            return SCALARS[hint], False
        if typing.is_typeddict(hint):
            return hint.__name__, False
        if origin is typing.Literal:
            name = nested_type_name(key)
            values = typing.get_args(hint)
            if self.enums.setdefault(name, values) != values:
                raise ValueError(f"{self.cls.__name__}.{key}: two Literals named {name}")
            return name, False
        if origin is list:
            [item] = typing.get_args(hint)
            inner, nullable = self.swift_type(item, key)
            return f"[{inner}{'?' if nullable else ''}]", False
        if origin is dict:
            key_type, item = typing.get_args(hint)
            if key_type is not str:
                raise ValueError(f"{self.cls.__name__}.{key}: a JSON object has string keys")
            inner, nullable = self.swift_type(item, key)
            return f"[String: {inner}{'?' if nullable else ''}]", False
        raise ValueError(f"{self.cls.__name__}.{key}: unsupported annotation {hint}")

    def render(self) -> str:
        hints = typing.get_type_hints(self.cls)
        required = self.cls.__required_keys__
        fields = []
        for key, hint in hints.items():
            swift, nullable = self.swift_type(hint, key)
            fields.append((key, property_name(key), swift, nullable, key in required))
        lines = [f"    struct {self.cls.__name__}: Codable, Hashable, Sendable {{"]
        for _key, name, swift, nullable, is_required in fields:
            optional = "?" if nullable or not is_required else ""
            lines.append(f"        public let {name}: {swift}{optional}")
        for enum_name, values in self.enums.items():
            lines.append("")
            lines.extend("    " + line for line in literal_enum(enum_name, values).splitlines())
        lines.append("")
        lines.append("        enum CodingKeys: String, CodingKey {")
        lines.extend(f"            case {name} = {json.dumps(key)}" for key, name, *_ in fields)
        lines.append("        }")
        lines.append("")
        lines.append("        public init(from decoder: any Decoder) throws {")
        lines.append("            let container = try decoder.container(keyedBy: CodingKeys.self)")
        for _key, name, swift, nullable, is_required in fields:
            bare = name.strip("`")
            if not is_required:
                lines.append(f"            {name} = try container.decodeIfPresent({swift}.self, forKey: .{bare})")
            elif nullable:
                lines.append(f"            {name} = try container.decode({swift}?.self, forKey: .{bare})")
            else:
                lines.append(f"            {name} = try container.decode({swift}.self, forKey: .{bare})")
        lines.append("        }")
        lines.append("")
        lines.append("        public func encode(to encoder: any Encoder) throws {")
        lines.append("            var container = encoder.container(keyedBy: CodingKeys.self)")
        for _key, name, _swift, _nullable, is_required in fields:
            bare = name.strip("`")
            method = "encode" if is_required else "encodeIfPresent"
            lines.append(f"            try container.{method}({name}, forKey: .{bare})")
        lines.append("        }")
        lines.append("    }")
        return "\n".join(lines)


def literal_enum(name: str, values: tuple[str, ...]) -> str:
    cases = [(case_name(value), value) for value in values]
    lines = [f"    public enum {name}: Codable, Hashable, Sendable {{"]
    lines.extend(f"        case {case}" for case, _ in cases)
    lines.append("        /// A value this build does not know yet: the server is newer than the app.")
    lines.append("        case unknown(String)")
    lines.append("")
    lines.append("        public init(rawValue: String) {")
    lines.append("            switch rawValue {")
    lines.extend(f"            case {json.dumps(value)}: self = .{case.strip('`')}" for case, value in cases)
    lines.append("            default: self = .unknown(rawValue)")
    lines.append("            }")
    lines.append("        }")
    lines.append("")
    lines.append("        public var rawValue: String {")
    lines.append("            switch self {")
    lines.extend(f"            case .{case.strip('`')}: {json.dumps(value)}" for case, value in cases)
    lines.append("            case .unknown(let rawValue): rawValue")
    lines.append("            }")
    lines.append("        }")
    lines.append("")
    lines.append("        public init(from decoder: any Decoder) throws {")
    lines.append("            self.init(rawValue: try decoder.singleValueContainer().decode(String.self))")
    lines.append("        }")
    lines.append("")
    lines.append("        public func encode(to encoder: any Encoder) throws {")
    lines.append("            var container = encoder.singleValueContainer()")
    lines.append("            try container.encode(rawValue)")
    lines.append("        }")
    lines.append("    }")
    return "\n".join(lines)


def union_enum(name: str, members: tuple[type, ...]) -> str:
    tagged = discriminator(members)
    if tagged is None:
        return untagged_enum(name, members)
    key, values = tagged
    cases = [(member_case(member, members, name), member) for member in members]
    lines = [f"    enum {name}: Codable, Hashable, Sendable {{"]
    lines.extend(f"        case {case}({member.__name__})" for case, member in cases)
    lines.append(f"        /// A `{key}` this build does not know yet: the server is newer than the app.")
    lines.append("        case unknown(String)")
    lines.append("")
    lines.append("        private enum Tag: String, CodingKey {")
    lines.append(f"            case tag = {json.dumps(key)}")
    lines.append("        }")
    lines.append("")
    lines.append("        public init(from decoder: any Decoder) throws {")
    lines.append("            let tag = try decoder.container(keyedBy: Tag.self).decode(String.self, forKey: .tag)")
    lines.append("            switch tag {")
    for case, member in cases:
        labels = ", ".join(json.dumps(value) for value in values[member])
        lines.append(f"            case {labels}: self = .{case.strip('`')}(try {member.__name__}(from: decoder))")
    lines.append("            default: self = .unknown(tag)")
    lines.append("            }")
    lines.append("        }")
    lines.append("")
    lines.append("        public func encode(to encoder: any Encoder) throws {")
    lines.append("            switch self {")
    for case, _member in cases:
        lines.append(f"            case .{case.strip('`')}(let value): try value.encode(to: encoder)")
    lines.append("            case .unknown(let tag):")
    lines.append("                var container = encoder.container(keyedBy: Tag.self)")
    lines.append("                try container.encode(tag, forKey: .tag)")
    lines.append("            }")
    lines.append("        }")
    lines.append("    }")
    return "\n".join(lines)


def untagged_enum(name: str, members: tuple[type, ...]) -> str:
    """A union nothing tags: each shape is tried in turn, the one with the most required
    keys first, since a smaller shape would also accept a larger one's object."""
    ordered = sorted(members, key=lambda member: -len(member.__required_keys__))
    keys = [set(member.__required_keys__) for member in ordered]
    if any(earlier <= later for index, earlier in enumerate(keys) for later in keys[index + 1:]):
        raise ValueError(f"{name}: a shape tried first would accept a later one")
    cases = [(member_case(member, members, name), member) for member in ordered]
    lines = [f"    enum {name}: Codable, Hashable, Sendable {{"]
    lines.extend(f"        case {case}({member.__name__})" for case, member in cases)
    lines.append("")
    lines.append("        public init(from decoder: any Decoder) throws {")
    for case, member in cases[:-1]:
        lines.append(f"            if let value = try? {member.__name__}(from: decoder) {{")
        lines.append(f"                self = .{case.strip('`')}(value)")
        lines.append("                return")
        lines.append("            }")
    last_case, last_member = cases[-1]
    lines.append(f"            self = .{last_case.strip('`')}(try {last_member.__name__}(from: decoder))")
    lines.append("        }")
    lines.append("")
    lines.append("        public func encode(to encoder: any Encoder) throws {")
    lines.append("            switch self {")
    for case, _member in cases:
        lines.append(f"            case .{case.strip('`')}(let value): try value.encode(to: encoder)")
    lines.append("            }")
    lines.append("        }")
    lines.append("    }")
    return "\n".join(lines)


def models() -> str:
    named_unions = unions()
    blocks = [Struct(cls, named_unions).render() for cls in typeddicts()]
    blocks += [union_enum(name, members) for members, name in named_unions.items()]
    return (HEADER + "\nimport Foundation\n\n"
            "/// What the notebook API serves, one type per declared view.\n"
            "public enum Notebook {}\n\n"
            "public extension Notebook {\n" + "\n\n".join(blocks) + "\n}\n")


def fixture(payload: Any) -> str:
    return json.dumps(payload, ensure_ascii=False, indent=2) + "\n"


def contract_tests() -> str:
    tests = "\n\n".join(
        f"    @Test func {camel(screen)}() throws {{\n"
        f"        try expectRoundTrip(Notebook.{shape.__name__}.self, fixture: {json.dumps(screen)})\n"
        f"    }}"
        for screen, (shape, _) in SCREENS.items())
    return (HEADER + "\nimport Testing\n@testable import RedlineKit\n\n"
            "/// Each screen's payload decodes, and encodes back to the same JSON.\n"
            "struct NotebookContractTests {\n" + tests + "\n}\n")


def outputs() -> Iterator[tuple[Path, str]]:
    yield MODELS, models()
    yield CONTRACT_TESTS, contract_tests()
    for screen, (_, payload) in SCREENS.items():
        yield FIXTURES / f"{screen}.json", fixture(payload)
    yield from ios_palette.outputs()


def strays() -> list[Path]:
    """Fixtures and colour sets this module no longer writes."""
    expected = dict(outputs())
    return [path for path in sorted(FIXTURES.glob("*.json")) if path not in expected] + ios_palette.stray()


def stale_or_stray() -> list[str]:
    """The written files that differ from what this module writes, and fixtures it no
    longer writes."""
    found = [path.relative_to(IOS).as_posix() for path, text in outputs()
             if not path.is_file() or path.read_text(encoding="utf-8") != text]
    return found + [path.relative_to(IOS).as_posix() for path in strays()]


def main() -> None:
    for path in strays():
        if path.is_dir():
            for child in path.iterdir():
                child.unlink()
            path.rmdir()
        else:
            path.unlink()
    for path, text in outputs():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")
        print(path.relative_to(IOS.parent))


if __name__ == "__main__":
    main()
