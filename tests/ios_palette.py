ACCENT = "tartan"
HEX = re.compile(r"--([a-z0-9-]+):\s*(#[0-9a-fA-F]{6})\s*;")
ALIAS = re.compile(r"--([a-z0-9-]+):\s*var\(--([a-z0-9-]+)\)\s*;")
MIX = re.compile(r"--([a-z0-9-]+):\s*color-mix\(in oklab, var\(--([a-z0-9-]+)\) (\d+)%, var\(--([a-z0-9-]+)\)\)\s*;")


def _block(css: str, selector: str) -> str:
    start = css.index(selector + " {") + len(selector) + 2
    return css[start:css.index("}", start)]


def palettes(css: str | None = None) -> tuple[dict[str, str], dict[str, str]]:
    """The light and dark values of every token, as `#rrggbb`. The dark block lists only
    the colours that change, and its media-query copy must say the same; derived tokens
    (`--over` mixes red and ink, `--z5` is red) are derived again in each palette."""
    css = css if css is not None else TOKENS.read_text(encoding="utf-8")
    light_block = _block(css, ":root")
    dark_block = _block(css, ':root[data-theme="dark"]')
    if HEX.findall(dark_block) != HEX.findall(_block(css, ':root:not([data-theme="light"])')):
        raise ValueError("tokens.css: the two dark blocks disagree")
    plain = {name: value.lower() for name, value in HEX.findall(light_block)}
    shaded = plain | {name: value.lower() for name, value in HEX.findall(dark_block)}
    return _derive(plain, light_block), _derive(shaded, light_block)


def _derive(values: dict[str, str], rules: str) -> dict[str, str]:
    values = dict(values)
    for name, first, share, second in MIX.findall(rules):
        values[name] = mix(values[first], values[second], int(share) / 100)
    for name, target in ALIAS.findall(rules):
        values[name] = values[target]
    return values


# ------------------------------------------------------------ Oklab, as CSS mixes it
def _linear(channel: float) -> float:
    return channel / 12.92 if channel <= 0.04045 else ((channel + 0.055) / 1.055) ** 2.4


def _gamma(channel: float) -> float:
    channel = min(max(channel, 0.0), 1.0)
    return channel * 12.92 if channel <= 0.0031308 else 1.055 * channel ** (1 / 2.4) - 0.055


def _oklab(hex_colour: str) -> tuple[float, float, float]:
    r, g, b = (_linear(int(hex_colour[i:i + 2], 16) / 255) for i in (1, 3, 5))
    l_ = (0.4122214708 * r + 0.5363325363 * g + 0.0514459929 * b) ** (1 / 3)
    m_ = (0.2119034982 * r + 0.6806995451 * g + 0.1073969566 * b) ** (1 / 3)
    s_ = (0.0883024619 * r + 0.2817188376 * g + 0.6299787005 * b) ** (1 / 3)
    return (0.2104542553 * l_ + 0.7936177850 * m_ - 0.0040720468 * s_,
            1.9779984951 * l_ - 2.4285922050 * m_ + 0.4505937099 * s_,
            0.0259040371 * l_ + 0.7827717662 * m_ - 0.8086757660 * s_)


def _srgb(lab: tuple[float, float, float]) -> str:
    lightness, a, b = lab
    l_ = (lightness + 0.3963377774 * a + 0.2158037573 * b) ** 3
    m_ = (lightness - 0.1055613458 * a - 0.0638541728 * b) ** 3
    s_ = (lightness - 0.0894841775 * a - 1.2914855480 * b) ** 3
    rgb = (4.0767416621 * l_ - 3.3077115913 * m_ + 0.2309699292 * s_,
           -1.2684380046 * l_ + 2.6097574011 * m_ - 0.3413193965 * s_,
           -0.0041960863 * l_ - 0.7034186147 * m_ + 1.7076147010 * s_)
    return "#" + "".join(f"{round(_gamma(channel) * 255):02x}" for channel in rgb)


def mix(first: str, second: str, share: float) -> str:
    """`color-mix(in oklab, first share, second)`."""
    a, b = _oklab(first), _oklab(second)
    return _srgb(tuple(share * x + (1 - share) * y for x, y in zip(a, b, strict=True)))


# ------------------------------------------------------------ the files
def camel(token: str) -> str:
    head, *rest = token.split("-")
    return head + "".join(part.capitalize() for part in rest)


def _components(hex_colour: str) -> dict:
    return {"color-space": "srgb", "components": {
        "alpha": "1.000",
        "red": f"0x{hex_colour[1:3].upper()}",
        "green": f"0x{hex_colour[3:5].upper()}",
        "blue": f"0x{hex_colour[5:7].upper()}",
    }}


def colour_set(light: str, dark: str) -> str:
    contents = {
        "colors": [
            {"color": _components(light), "idiom": "universal"},
            {"appearances": [{"appearance": "luminosity", "value": "dark"}],
             "color": _components(dark), "idiom": "universal"},
        ],
        "info": {"author": "xcode", "version": 1},
    }
    return json.dumps(contents, indent=2) + "\n"


def _folder() -> str:
    return json.dumps({"info": {"author": "xcode", "version": 1}}, indent=2) + "\n"


def palette_swift() -> str:
    lines = [HEADER, "import SwiftUI", "",
             "/// The Redline palette, light and dark, from `tokens.css`.",
             "enum Palette {"]
    for token, meaning in TOKENS_USED.items():
        lines.append(f"    /// {meaning}")
        lines.append(f'    static let {camel(token)} = Color("Palette/{token}")')
    lines.append("}")
    return "\n".join(lines) + "\n"


def outputs() -> Iterator[tuple[Path, str]]:
    light, dark = palettes()
    yield ASSETS / "Contents.json", _folder()
    yield ASSETS / "Palette" / "Contents.json", json.dumps(
        {"info": {"author": "xcode", "version": 1}, "properties": {"provides-namespace": True}},
        indent=2) + "\n"
    for token in TOKENS_USED:
        yield ASSETS / "Palette" / f"{token}.colorset" / "Contents.json", colour_set(light[token], dark[token])
    yield ASSETS / "AccentColor.colorset" / "Contents.json", colour_set(light[ACCENT], dark[ACCENT])
    yield PALETTE_SWIFT, palette_swift()


def stray() -> list[Path]:
    """Colour sets left from a token the app no longer uses."""
    expected = {path.parent for path, _ in outputs() if path.parent.suffix == ".colorset"}
    return sorted(path for path in (ASSETS / "Palette").glob("*.colorset") if path not in expected)
