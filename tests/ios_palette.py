"""The iOS app's palette, written from `src/redline/cards/tokens.css`.

The cards, the page and the app share one set of colours, declared once in `tokens.css`. This
module turns its light and dark blocks into an asset catalogue under `ios/Redline/` (one
colour set per token, light and dark), the app's accent colour (the tartan), and
`Design/Palette.swift`, which names them. `--over`, a `color-mix` in the CSS, is mixed here
the same way, in Oklab. tests/ios_contract.py writes these files with the rest of the iOS
side, and tests/test_ios_contract.py fails while they are stale.
"""

